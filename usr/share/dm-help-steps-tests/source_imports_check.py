#!/usr/bin/python3 -Bsu
"""Flag a shell script that CALLS a library function without DIRECTLY SOURCING
the file that defines it -- the has.bsh-in-5200_prepare-release bug class.

POLICY (project rule): each script declares its OWN imports: "needs xyz -> source
xyz". No transitive reliance ("x sources y which sources z"). So only DIRECT
sources count.

Detection is shfmt-AST based (shfmt --to-json), never regex: a call is a
CallExpr whose first word is a single literal; a definition is a FuncDecl;
comments, string bodies, redirects and heredocs are separate AST nodes and are
never mistaken for calls. This avoids reinventing a bash parser.

Vocabulary = functions defined in a file that is sourced somewhere (an
importable library), minus names installed as executables on PATH (bin/sbin) --
those are external commands, not imports.

Source matching is by BASENAME (deliberate: a source path is often built from a
variable, e.g. "${HELPER_SCRIPTS_PATH:-}"/.../has.bsh, so the full path cannot be
resolved statically). Trade-off: if two different files share a basename, a
consumer that sources one is credited for a function defined in the other. In
this tree library basenames are unique, so this does not occur; resolving full
paths would reintroduce the dynamic-path problem the basename approach avoids.

The gate FAILS (exit 1) on a GENUINE RUNTIME BREAK in a top-level script: a call
reachable via no source path, direct or transitive -- it actually fails at
runtime. Known-but-unfixed breaks live in an allowlist file (file<TAB>func, one
per line, '#' comments); an allowlisted break that no longer occurs (stale) also
fails, so fixes must drop their entry. Fragment/policy/uncertain findings are
reported for visibility but do not gate.
"""
import json
import os
import re
import subprocess
import sys

SHELL_EXT = (".sh", ".bsh")
# a shebang interpreter we treat as bash-compatible for shfmt. Excludes zsh,
# csh, fish, etc. -- shfmt cannot parse those, so they are not shell files here.
_SHEBANG_RE = re.compile(rb"^#!\s*(\S+)(?:\s+(\S+))?")
_SHELL_INTERP = {b"sh", b"bash", b"dash"}
_PH = "\x00"   # placeholder for a ${var}/$(...)/$var in a path

COMMON_EXTERNAL = {
    "sync", "yad", "notify-send", "kdialog", "install", "sleep", "mount",
    "ping", "true", "false", "test", "time",
}
EXCLUDE_SUBSTR = ("/grml-debootstrap", "grml-debootstraptest")


def is_generated(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(2000).lower()
    except OSError:
        return False
    return ("autogenerated" in head or "do not edit" in head
            or "automatically generated" in head)


def is_shell_file(path):
    if path.endswith(SHELL_EXT):
        return True
    if "." in os.path.basename(path):
        return False
    try:
        with open(path, "rb") as fh:
            first = fh.readline()
    except OSError:
        return False
    m = _SHEBANG_RE.match(first)
    if not m:
        return False
    interp = m.group(1).rsplit(b"/", 1)[-1]
    if interp == b"env" and m.group(2):
        interp = m.group(2).rsplit(b"/", 1)[-1]
    return interp in _SHELL_INTERP


def collect(root):
    files, commands = [], set()
    for dirpath, dirnames, filenames in os.walk(root):
        if ".git" in dirnames:
            dirnames.remove(".git")
        for fn in filenames:
            p = os.path.join(dirpath, fn)
            if "/bin/" in p + "/" or "/sbin/" in p + "/":
                commands.add(os.path.basename(p))
            if os.path.islink(p):
                continue
            if is_shell_file(p):
                files.append(p)
    return files, commands


def parse_ast(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            src = fh.read()
        out = subprocess.run(
            ["shfmt", "--to-json", "-ln", "bash"],
            input=src, capture_output=True, text=True, timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if out.returncode != 0:
        return None
    try:
        return json.loads(out.stdout)
    except json.JSONDecodeError:
        return None


def word_literalish(word):
    out = []
    for part in (word or {}).get("Parts", []):
        t = part.get("Type")
        if t in ("Lit", "SglQuoted"):
            out.append(part.get("Value", ""))
        elif t == "DblQuoted":
            out.append(word_literalish(part))
        else:
            out.append(_PH)
    return "".join(out)


def call_name(call):
    args = call.get("Args") or []
    if not args:
        return None
    parts = args[0].get("Parts") or []
    if len(parts) == 1 and parts[0].get("Type") == "Lit":
        return parts[0].get("Value")
    return None


def source_basename(call):
    args = call.get("Args") or []
    if len(args) < 2:
        return None
    seg = word_literalish(args[1]).rsplit("/", 1)[-1]
    if not seg or _PH in seg:
        return None
    return seg


def extract(ast):
    """Return (defs, calls, sources, unresolved) where calls is a list of
    (name, line, top_level) and sources is a list of (basename, line).
    top_level is False when the call is lexically inside a function body: such a
    call runs when the function is invoked (after top-level sourcing), so source
    order does not constrain it; a top_level call must be preceded by its
    source."""
    defs: set = set()
    calls: list = []
    sources: list = []
    unresolved = False

    def rec(node, in_func):
        nonlocal unresolved
        if isinstance(node, dict):
            t = node.get("Type")
            if t == "FuncDecl":
                name = (node.get("Name") or {}).get("Value")
                if name:
                    defs.add(name)
                for v in node.values():
                    rec(v, True)
                return
            if t == "CallExpr":
                name = call_name(node)
                if name is not None:
                    line = node["Pos"]["Line"]
                    if name in (".", "source"):
                        base = source_basename(node)
                        if base is None:
                            unresolved = True
                        else:
                            sources.append((base, line))
                    else:
                        calls.append((name, line, not in_func))
                for v in node.values():
                    rec(v, in_func)
                return
            for v in node.values():
                rec(v, in_func)
        elif isinstance(node, list):
            for v in node:
                rec(v, in_func)

    rec(ast, False)
    return defs, calls, sources, unresolved


def transitive(base, sources_of, seen=None):
    if seen is None:
        seen = set()
    for b in sources_of.get(base, ()):
        if b not in seen:
            seen.add(b)
            transitive(b, sources_of, seen)
    return seen


def read_allowlist(path):
    allow: dict = {}
    if not path or not os.path.isfile(path):
        return allow
    with open(path, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) == 2:
                allow[(parts[0].strip(), parts[1].strip())] = raw.strip()
    return allow


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: source_imports_check.py <derivative-maker-dir> "
                 "[allowlist-file]")
    root = os.path.abspath(sys.argv[1])
    allow_path = sys.argv[2] if len(sys.argv) > 2 else None
    if not os.path.isdir(root):
        print(f"FATAL: not a directory: {root}", file=sys.stderr)
        sys.exit(2)
    if subprocess.run(["sh", "-c", "command -v shfmt"],
                      capture_output=True).returncode != 0:
        print("FATAL: shfmt not installed (required for AST parsing)",
              file=sys.stderr)
        sys.exit(2)

    files, commands = collect(root)
    defs_by_name: dict = {}
    sources_of: dict = {}
    file_defs, file_calls = {}, {}
    file_direct, file_src_min, file_unresolved = {}, {}, {}
    scanned_rel: set = set()
    unparsed = []
    for p in files:
        ast = parse_ast(p)
        if ast is None:
            unparsed.append(os.path.relpath(p, root))
            continue
        defs, calls, srcs, unresolved = extract(ast)
        base = os.path.basename(p)
        scanned_rel.add(os.path.relpath(p, root))
        src_bases = {b for b, _ in srcs}
        src_min: dict = {}
        for b, ln in srcs:
            if b not in src_min or ln < src_min[b]:
                src_min[b] = ln
        file_defs[p], file_calls[p] = defs, calls
        file_direct[p], file_src_min[p] = src_bases, src_min
        file_unresolved[p] = unresolved
        for d in defs:
            defs_by_name.setdefault(d, set()).add(base)
        sources_of.setdefault(base, set()).update(src_bases)

    library_basenames = set()
    for s in sources_of.values():
        library_basenames |= s
    vocab = {n for n, b in defs_by_name.items()
             if (b & library_basenames) and n not in commands}

    brk_top, brk_frag, pol, unc, lo = [], [], [], [], []
    for p in file_calls:
        if any(x in p for x in EXCLUDE_SUBSTR) or is_generated(p):
            continue
        local, direct = file_defs[p], file_direct[p]
        is_frag = os.path.basename(p) in library_basenames
        trans = transitive(os.path.basename(p), sources_of)
        rel = os.path.relpath(p, root)
        for name, line, top_level in file_calls[p]:
            if name not in vocab or name in local:
                continue
            db = defs_by_name[name]
            if db & direct:
                # directly sources a definer. An in-function call is fine (runs
                # after top-level sourcing); a TOP-LEVEL call must be preceded by
                # the source, else it runs before the definer loads.
                if not top_level:
                    continue
                earliest = min((file_src_min[p][b] for b in db
                                if b in file_src_min[p]), default=line + 1)
                if earliest < line:
                    continue
                brk_top.append((rel, line, name))   # sourced after the call
                continue
            rec = (rel, line, name)
            if name in COMMON_EXTERNAL:
                lo.append(rec)
            elif db & trans:
                pol.append(rec)
            elif file_unresolved[p]:
                unc.append(rec)
            elif is_frag:
                brk_frag.append(rec)
            else:
                brk_top.append(rec)

    for title, recs in (
        ("TOP-LEVEL BREAK", brk_top),
        ("FRAGMENT BREAK (parent provides it; policy)", brk_frag),
        ("POLICY-ONLY (works transitively)", pol),
        ("UNCERTAIN (unresolved ${var} source)", unc),
        ("LOW-CONFIDENCE (shadows external command)", lo),
    ):
        print(f"##### {title}: {len(set(recs))} #####", file=sys.stderr)
        for rel, line, name in sorted(set(recs)):
            print(f"  {rel}:{line}: {name}", file=sys.stderr)

    allow = read_allowlist(allow_path)
    active = {(rel, name) for rel, _, name in brk_top}
    unexpected = sorted(active - set(allow))
    ## An allowlist entry is stale only when its file was actually scanned yet no
    ## longer breaks -- NOT when the file is absent (e.g. an uninitialized
    ## submodule), which would otherwise fail the gate for a missing subtree.
    stale = sorted(e for e in (set(allow) - active) if e[0] in scanned_rel)
    absent = sorted(e for e in (set(allow) - active) if e[0] not in scanned_rel)
    for rel, name in absent:
        print(f"INFO: allowlist entry's file not present (kept): {rel} '{name}'",
              file=sys.stderr)

    ## A file shfmt cannot parse is dropped from analysis, so a break inside it
    ## is invisible. List each one LOUDLY (not just a count) so the coverage gap
    ## is visible for review rather than silently passing. Not a hard fail:
    ## shfmt's parser has real limits and a red-for-no-reason gate is its own
    ## fabricated signal; an allowlisted-but-unparsed file is handled above
    ## (kept, not stale).
    for rel in sorted(unparsed):
        print(f"WARN: shfmt could not parse (NOT checked for breaks): {rel}",
              file=sys.stderr)

    for rel, name in unexpected:
        print(f"FAIL: top-level break not allowlisted: {rel} calls '{name}' "
              f"with no source providing it", file=sys.stderr)
    for rel, name in stale:
        print(f"FAIL: stale allowlist entry (no longer breaks -- remove it): "
              f"{rel}\\t{name}", file=sys.stderr)
    if unexpected or stale:
        sys.exit(1)
    print(f"OK: {len(active)} top-level break(s), all allowlisted; "
          f"{len(unparsed)} file(s) unparsed (listed above if any)",
          file=sys.stderr)
    sys.exit(0)


if __name__ == "__main__":
    main()
