#!/usr/bin/python3 -Bsu
"""Flag a shell script that CALLS a library function without DIRECTLY SOURCING
the file that defines it -- the has.bsh-in-5200_prepare-release bug class.

POLICY (project rule): each script declares its OWN imports: "needs xyz -> source
xyz". No transitive reliance ("x sources y which sources z"). So only DIRECT
sources count.

Detection is shfmt-AST based (shfmt --to-json), never regex: a call is a
CallExpr whose first word is a single literal; a definition is a FuncDecl;
comments, string bodies, redirects and heredocs are separate AST nodes and are
never mistaken for calls. This avoids reinventing a bash parser.

Vocabulary = functions defined in a file that is sourced somewhere (an
importable library), minus names installed as executables on PATH (bin/sbin) --
those are external commands, not imports.

The gate FAILS (exit 1) on a GENUINE RUNTIME BREAK in a top-level script: a call
reachable via no source path, direct or transitive -- it actually fails at
runtime. Known-but-unfixed breaks live in an allowlist file (file<TAB>func, one
per line, '#' comments); an allowlisted break that no longer occurs (stale) also
fails, so fixes must drop their entry. Fragment/policy/uncertain findings are
reported for visibility but do not gate.
"""
import json
import os
import subprocess
import sys

SHELL_EXT = (".sh", ".bsh")
_PH = "\x00"   # placeholder for a ${var}/$(...)/$var in a path

COMMON_EXTERNAL = {
    "sync", "yad", "notify-send", "kdialog", "install", "sleep", "mount",
    "ping", "true", "false", "test", "time",
}
EXCLUDE_SUBSTR = ("/grml-debootstrap", "grml-debootstraptest")


def is_generated(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            head = fh.read(2000).lower()
    except OSError:
        return False
    return ("autogenerated" in head or "do not edit" in head
            or "automatically generated" in head)


def is_shell_file(path):
    if path.endswith(SHELL_EXT):
        return True
    if "." in os.path.basename(path):
        return False
    try:
        with open(path, "rb") as fh:
            first = fh.readline()
    except OSError:
        return False
    return first.startswith(b"#!") and (b"bash" in first or b"sh" in first)


def collect(root):
    files, commands = [], set()
    for dirpath, dirnames, filenames in os.walk(root):
        if ".git" in dirnames:
            dirnames.remove(".git")
        for fn in filenames:
            p = os.path.join(dirpath, fn)
            if "/bin/" in p + "/" or "/sbin/" in p + "/":
                commands.add(os.path.basename(p))
            if os.path.islink(p):
                continue
            if is_shell_file(p):
                files.append(p)
    return files, commands


def parse_ast(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            src = fh.read()
        out = subprocess.run(
            ["shfmt", "--to-json", "-ln", "bash"],
            input=src, capture_output=True, text=True, timeout=30,
        )
    except (OSError, subprocess.TimeoutExpired):
        return None
    if out.returncode != 0:
        return None
    try:
        return json.loads(out.stdout)
    except json.JSONDecodeError:
        return None


def walk(node, visit):
    if isinstance(node, dict):
        visit(node)
        for v in node.values():
            walk(v, visit)
    elif isinstance(node, list):
        for v in node:
            walk(v, visit)


def word_literalish(word):
    out = []
    for part in (word or {}).get("Parts", []):
        t = part.get("Type")
        if t in ("Lit", "SglQuoted"):
            out.append(part.get("Value", ""))
        elif t == "DblQuoted":
            out.append(word_literalish(part))
        else:
            out.append(_PH)
    return "".join(out)


def call_name(call):
    args = call.get("Args") or []
    if not args:
        return None
    parts = args[0].get("Parts") or []
    if len(parts) == 1 and parts[0].get("Type") == "Lit":
        return parts[0].get("Value")
    return None


def source_basename(call):
    args = call.get("Args") or []
    if len(args) < 2:
        return None
    seg = word_literalish(args[1]).rsplit("/", 1)[-1]
    if not seg or _PH in seg:
        return None
    return seg


def extract(ast):
    defs, calls, sources, unresolved = set(), [], set(), False

    def visit(n):
        nonlocal unresolved
        t = n.get("Type")
        if t == "FuncDecl":
            name = (n.get("Name") or {}).get("Value")
            if name:
                defs.add(name)
        elif t == "CallExpr":
            name = call_name(n)
            if name is None:
                return
            if name in (".", "source"):
                base = source_basename(n)
                if base is None:
                    unresolved = True
                else:
                    sources.add(base)
            else:
                calls.append((name, n["Pos"]["Line"]))

    walk(ast, visit)
    return defs, calls, sources, unresolved


def transitive(base, sources_of, seen=None):
    if seen is None:
        seen = set()
    for b in sources_of.get(base, ()):
        if b not in seen:
            seen.add(b)
            transitive(b, sources_of, seen)
    return seen


def read_allowlist(path):
    allow: dict = {}
    if not path or not os.path.isfile(path):
        return allow
    with open(path, "r", encoding="utf-8") as fh:
        for raw in fh:
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            parts = line.split("\t")
            if len(parts) == 2:
                allow[(parts[0].strip(), parts[1].strip())] = raw.strip()
    return allow


def main():
    if len(sys.argv) < 2:
        sys.exit("usage: source_imports_check.py <derivative-maker-dir> "
                 "[allowlist-file]")
    root = os.path.abspath(sys.argv[1])
    allow_path = sys.argv[2] if len(sys.argv) > 2 else None
    if not os.path.isdir(root):
        print(f"FATAL: not a directory: {root}", file=sys.stderr)
        sys.exit(2)
    if subprocess.run(["sh", "-c", "command -v shfmt"],
                      capture_output=True).returncode != 0:
        print("FATAL: shfmt not installed (required for AST parsing)",
              file=sys.stderr)
        sys.exit(2)

    files, commands = collect(root)
    defs_by_name: dict = {}
    sources_of: dict = {}
    file_defs, file_calls = {}, {}
    file_direct, file_unresolved = {}, {}
    unparsed = []
    for p in files:
        ast = parse_ast(p)
        if ast is None:
            unparsed.append(p)
            continue
        defs, calls, srcs, unresolved = extract(ast)
        base = os.path.basename(p)
        file_defs[p], file_calls[p] = defs, calls
        file_direct[p], file_unresolved[p] = srcs, unresolved
        for d in defs:
            defs_by_name.setdefault(d, set()).add(base)
        sources_of.setdefault(base, set()).update(srcs)

    library_basenames = set()
    for s in sources_of.values():
        library_basenames |= s
    vocab = {n for n, b in defs_by_name.items()
             if (b & library_basenames) and n not in commands}

    brk_top, brk_frag, pol, unc, lo = [], [], [], [], []
    for p in file_calls:
        if any(x in p for x in EXCLUDE_SUBSTR) or is_generated(p):
            continue
        local, direct = file_defs[p], file_direct[p]
        is_frag = os.path.basename(p) in library_basenames
        trans = transitive(os.path.basename(p), sources_of)
        rel = os.path.relpath(p, root)
        for name, line in file_calls[p]:
            if name not in vocab or name in local:
                continue
            db = defs_by_name[name]
            if db & direct:
                continue
            rec = (rel, line, name)
            if name in COMMON_EXTERNAL:
                lo.append(rec)
            elif db & trans:
                pol.append(rec)
            elif file_unresolved[p]:
                unc.append(rec)
            elif is_frag:
                brk_frag.append(rec)
            else:
                brk_top.append(rec)

    for title, recs in (
        ("TOP-LEVEL BREAK", brk_top),
        ("FRAGMENT BREAK (parent provides it; policy)", brk_frag),
        ("POLICY-ONLY (works transitively)", pol),
        ("UNCERTAIN (unresolved ${var} source)", unc),
        ("LOW-CONFIDENCE (shadows external command)", lo),
    ):
        print(f"##### {title}: {len(set(recs))} #####", file=sys.stderr)
        for rel, line, name in sorted(set(recs)):
            print(f"  {rel}:{line}: {name}", file=sys.stderr)

    allow = read_allowlist(allow_path)
    active = {(rel, name) for rel, _, name in brk_top}
    unexpected = sorted(active - set(allow))
    stale = sorted(set(allow) - active)

    for rel, name in unexpected:
        print(f"FAIL: top-level break not allowlisted: {rel} calls '{name}' "
              f"with no source providing it", file=sys.stderr)
    for rel, name in stale:
        print(f"FAIL: stale allowlist entry (no longer breaks -- remove it): "
              f"{rel}\\t{name}", file=sys.stderr)
    if unexpected or stale:
        sys.exit(1)
    print(f"OK: {len(active)} top-level break(s), all allowlisted; "
          f"{len(unparsed)} file(s) unparsed", file=sys.stderr)
    sys.exit(0)


if __name__ == "__main__":
    main()
