## AI-Assisted

## strings.bsh random_alpha_numeric: the Tor stream-isolation password/token
## generator. Its output length is security-relevant -- a short value is a weak,
## more-predictable isolation credential -- so the function GUARANTEES exactly
## the requested byte count and fails loud (return 1) otherwise, for every
## caller (curl.anondist, dnf-3.anondist, ...). Asserted:
##   - default length 43 and an explicit count are honored, charset [A-Za-z0-9];
##   - a non-numeric count is rejected (return 1, "non-numeric byte count");
##   - the length guard fires when generation yields too few bytes (return 1,
##     "got N of M bytes") -- forced deterministically with a `head` stub that
##     truncates the stream, exercising the REAL guard rather than reimplementing
##     it.
##
## Sources the REAL strings.bsh. A missing library is a REQUIRED-dependency
## environment bug -> exit 1 (FATAL), never a skip.

set -o errexit
set -o nounset
set -o pipefail
set -o errtrace
shopt -s inherit_errexit
shopt -s shift_verbose
export LC_ALL=C

[ -v HELPER_SCRIPTS_REPO ] || HELPER_SCRIPTS_REPO=""

tree_root="${HELPER_SCRIPTS_REPO:-${HELPER_SCRIPTS_PATH:-}}"
tree_root="${tree_root%/}"
strings_bsh="${tree_root}/usr/libexec/helper-scripts/strings.bsh"

if [ ! -r "${strings_bsh}" ]; then
   printf '%s\n' "FATAL: strings.bsh not readable at '${strings_bsh}'" >&2
   printf '%s\n' "set HELPER_SCRIPTS_REPO (or HELPER_SCRIPTS_PATH) to a helper-scripts checkout, or install helper-scripts" >&2
   exit 1
fi

export HELPER_SCRIPTS_PATH="${tree_root}"

## The reject path calls 'sanitize-echo' (a python tool); resolve it and its
## module from the tree under test.
if [ -n "${tree_root}" ]; then
   PATH="${tree_root}/usr/bin:${PATH}"
   export PATH
   PYTHONPATH="${tree_root}/usr/lib/python3/dist-packages${PYTHONPATH:+:${PYTHONPATH}}"
   export PYTHONPATH
fi

# shellcheck disable=SC1090,SC1091
source "${strings_bsh}"

if [ "$(type -t random_alpha_numeric)" != 'function' ]; then
   printf '%s\n' "FATAL: sourcing '${strings_bsh}' defined no 'random_alpha_numeric'" >&2
   exit 1
fi

test_dir="$(mktemp --directory)"
cleanup_handler() {
   ## '|| true': a cleanup failure must not clobber the script's real exit code.
   safe-rm -r -f -- "${test_dir}" || true
}
trap cleanup_handler EXIT

pass=0
fail=0
check() {
   local label="$1" got="$2" want="$3"
   if [ "${got}" = "${want}" ]; then
      printf '%s\n' "PASS: ${label}"
      pass=$((pass + 1))
   else
      printf '%s\n' "FAIL: ${label} (got '${got}', want '${want}')"
      fail=$((fail + 1))
   fi
}

## --- Contract: length + charset. ---
value_default="$(random_alpha_numeric)"
check "default length 43" "${#value_default}" "43"

value_ten="$(random_alpha_numeric 10)"
check "explicit count 10 -> length 10" "${#value_ten}" "10"

if [[ "${value_default}" =~ ^[A-Za-z0-9]+$ ]]; then
   charset=ok
else
   charset=bad
fi
check "charset [A-Za-z0-9]" "${charset}" "ok"

## --- A non-numeric count is rejected. ---
## random_alpha_numeric's reject diagnostic goes through
## sanitize-echo --max-length "${STRINGS_BSH_REPORT_MAX}", and the message is
## prefixed with $0 (this script's absolute path). From a deep checkout, $0 alone
## can exceed the default 200-char cap and truncate the phrase matched below,
## failing on correct code. Raise the cap so the match is path-independent.
# shellcheck disable=SC2034  # read by random_alpha_numeric in the sourced strings.bsh
STRINGS_BSH_REPORT_MAX=100000
rc=0
err="$(random_alpha_numeric abc 2>&1 1>/dev/null)" || rc=$?
check "non-numeric count: return 1" "${rc}" "1"
case "${err}" in
   *"non-numeric byte count"*)
      nonnum_msg=ok
      ;;
   *)
      nonnum_msg=bad
      ;;
esac
check "non-numeric count: diagnostic emitted" "${nonnum_msg}" "ok"

## --- Length guard: too few generated bytes -> return 1, no short value. A
##     `head` stub truncates the random stream to 5 bytes, so the requested 43
##     cannot be met and the REAL guard must fire. ---
stub_bin="${test_dir}/stubbin"
mkdir -p -- "${stub_bin}"
## Literal shell written to a file; $-expressions expand when the stub runs.
## Emit a fixed short value and exit WITHOUT reading stdin -- draining it would
## read /dev/random forever (no EOF). Exiting closes the pipe, so the upstream
## `tr </dev/random` dies on SIGPIPE, which random_alpha_numeric absorbs.
# shellcheck disable=SC2016
{
   printf '%s\n' '#!/bin/bash'
   printf '%s\n' "printf '%s' abcde"
} > "${stub_bin}/head"
chmod 0755 -- "${stub_bin}/head"

rc=0
err="$( export PATH="${stub_bin}:${PATH}"; random_alpha_numeric 2>&1 1>/dev/null )" || rc=$?
check "short generation: return 1" "${rc}" "1"
case "${err}" in
   *"got 5 of 43 bytes"*)
      short_msg=ok
      ;;
   *)
      short_msg=bad
      ;;
esac
check "short generation: 'got N of M bytes' diagnostic" "${short_msg}" "ok"

printf '%s\n' "" "${pass} pass, ${fail} fail, 0 skip"
if [ "${fail}" -ne 0 ]; then
   printf '%s\n' "FAILED"
   exit 1
fi
printf '%s\n' "OK"
