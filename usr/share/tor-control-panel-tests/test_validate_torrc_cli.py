"""
Regression tests for the real tcp-validate-torrc CLI (the privileged
tcp-write-torrc helper's validation gate).

Drives the ACTUAL helper from the checkout as a subprocess -- no stub, no root:
  * TCP_REPO/usr/libexec/tor-control-panel/tcp-validate-torrc is the entry point;
  * TCP_REPO/usr/lib/python3/dist-packages puts tor_control_panel on the path.
The CLI's contract is exit 0 = accepted, non-zero = rejected.

Two checks are @unittest.expectedFailure: they assert the behaviour the hardened
validator MUST have but does not yet (org-ai-assisted/tor-control-panel#17,
report-only on the app side). Each flips to XPASS -- suite red -- when the app is
fixed, the signal to drop the marker. See BUGS.md.
"""

import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path


def _repo() -> Path:
    ## TCP_REPO points at the tor-control-panel checkout under test; unset means
    ## the installed helper at the same path under '/'. The dist-ai runner always
    ## sets it, matching the other suites.
    repo = os.environ.get('TCP_REPO', '').strip()
    return Path(repo) if repo else Path('/')


## Resolve the real CLI once. A missing helper is an ENVIRONMENT bug (the suite
## cannot gate without it), so fail loud rather than skip -- mirrors tcp_testlib.
_VALIDATE_CLI = _repo() / 'usr/libexec/tor-control-panel/tcp-validate-torrc'
if not _VALIDATE_CLI.is_file():
    raise SystemExit(
        f"required helper not found: {_VALIDATE_CLI} "
        f"(set TCP_REPO to the tor-control-panel checkout)"
    )


def _validate(torrc_text) -> subprocess.CompletedProcess:
    """Run the real CLI on a torrc with the given text; return the result."""
    env = dict(os.environ)
    env['PYTHONPATH'] = str(_repo() / 'usr/lib/python3/dist-packages')
    with tempfile.TemporaryDirectory(prefix='tcp-validate-test-') as tmp:
        torrc_path = Path(tmp) / '40_tor_control_panel.conf'
        torrc_path.write_text(torrc_text, encoding='utf-8')
        return subprocess.run(
            [sys.executable, '-Bsu', str(_VALIDATE_CLI), str(torrc_path)],
            capture_output=True, text=True, env=env, timeout=30, check=False,
        )


def _validate_path(torrc_path) -> subprocess.CompletedProcess:
    """Run the real CLI on a given (possibly non-existent) path."""
    env = dict(os.environ)
    env['PYTHONPATH'] = str(_repo() / 'usr/lib/python3/dist-packages')
    return subprocess.run(
        [sys.executable, '-Bsu', str(_VALIDATE_CLI), str(torrc_path)],
        capture_output=True, text=True, env=env, timeout=30, check=False,
    )


_VALID_TORRC = (
    '## This file is generated by and should ONLY be used by '
    'tor-control-panel.\n'
    'DisableNetwork 0\n'
)

## A bridge torrc whose ClientTransportPlugin names an attacker-chosen exec path
## -- a directive the panel never emits. The exact example from issue #17.
_EXEC_INJECTION_TORRC = (
    'DisableNetwork 0\n'
    'UseBridges 1\n'
    'Bridge obfs4 10.0.0.1:443 ABCDEF cert=x iat-mode=0\n'
    'ClientTransportPlugin obfs4 exec /tmp/evil\n'
)


class TestValidateTorrcCli(unittest.TestCase):
    def test_valid_panel_torrc_accepted(self):
        result = _validate(_VALID_TORRC)
        self.assertEqual(
            result.returncode, 0,
            f"valid torrc rejected: {result.stdout}{result.stderr}",
        )

    def test_malformed_torrc_rejected(self):
        result = _validate('## header\nNotARealDirective @@@ garbage\n')
        self.assertNotEqual(
            result.returncode, 0,
            "malformed torrc was accepted; the validator rejects nothing",
        )

    @unittest.expectedFailure
    def test_transport_plugin_exec_is_rejected(self):
        ## KNOWN BUG (org-ai-assisted/tor-control-panel#17): tcpl_parse_torrc
        ## records only the ClientTransportPlugin transport NAME, not the exec
        ## path, so a panel-never-emitted 'exec /tmp/evil' validates clean and
        ## tcp-write-torrc would install it (Tor then launches /tmp/evil for that
        ## bridge). The validator must reject a torrc carrying directives/values
        ## the panel does not emit. XPASS here = the validator was hardened.
        result = _validate(_EXEC_INJECTION_TORRC)
        self.assertNotEqual(
            result.returncode, 0,
            "ClientTransportPlugin exec path accepted (config injection)",
        )

    @unittest.expectedFailure
    def test_not_a_file_message_interpolates_path(self):
        ## KNOWN BUG (org-ai-assisted/tor-control-panel#17, minor):
        ## tcp_validate_torrc.py:33 is a plain string, not an f-string, so the
        ## not-a-file error prints the literal '{str(torrc_path)}' instead of the
        ## path. XPASS here = the f-string was added.
        with tempfile.TemporaryDirectory(prefix='tcp-validate-test-') as tmp:
            missing = Path(tmp) / 'does-not-exist.conf'
            result = _validate_path(missing)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn(str(missing), result.stderr)
        self.assertNotIn('{str(torrc_path)}', result.stderr)


if __name__ == '__main__':
    unittest.main()
